n=int(input("Enter a number: "))
i=1
for i in range(1,11,1):
    a=n*i
    print(n, "*", i, "=", a)
# This code takes a number as input from the user and uses a for loop to calculate and print the multiplication table for that number from 1 to 10. The loop iterates through the numbers 1 to 10, multiplies the input number by the current iteration number, and prints the result in a formatted string.